"""Generate Week 10 presenter, visible-notes, and instructor-notes views."""
from pathlib import Path
import re

base = Path(__file__).resolve().parent
source = (base / "index.qmd").read_text()

for name, visible in (("presenter.qmd", "false"), ("with-notes.qmd", "true")):
    deck = source.replace("filters: [add-transitions.lua, strip-speaker-notes.lua]\n", "filters: [add-transitions.lua]\n")
    deck = deck.replace("  revealjs:\n", f"  revealjs:\n    show-notes: {visible}\n", 1)
    (base / name).write_text(deck)

intro = '''---
title: "Week 10: Instructor Notes"
subtitle: "Causality: Counterfactuals, Selection, and DAGs · COMM 5220"
format:
  html:
    theme: cosmo
    toc: true
    toc-depth: 3
    number-sections: false
    embed-resources: true
    css: notes.css
lang: en
---

[Open presenter slides](presenter.html) · [Open slides with visible notes](with-notes.html)

## Teaching approach

The seminar runs in five parts. **Part 1** opens with four claims that invite causal readings, each a different structure paired with evidence that tested it: social media and teen depression (reverse causation; Heffer et al. 2019), smoking and COVID in hospital studies (a collider; Griffith et al. 2020), TV and children's test scores (a common cause; Gentzkow and Shapiro 2008), and elite colleges and earnings (selection into treatment; Dale and Krueger 2002). Students generate alternative explanations before any vocabulary is introduced. **Part 2** defines causal effects with potential outcomes, using *Thinking Clearly with Data* chapter 3 (Body Vibes and flu-shot tables) and hormone replacement therapy as a real sign reversal. **Part 3** uses chapter 9's idea that a difference in means is an effect plus a baseline difference (without formal notation), with the Preuss lottery, elite colleges, police and crime, and signing the bias; it ends by separating selection into treatment from Week 9's selection into the sample. **Part 4** follows Rohrer's argument about DAGs: the three building blocks with simulations, the back-door criterion, control by design (including three communication studies), when control hurts (endogenous selection, mediators and PROCESS), and the limits of DAGs. **Part 5** redraws the opening cases, uses Bergstrom and West's fever example as the synthesis, presents Isch et al. (2026) on how often social scientists overclaim causality and how LLM summaries amplify it, discusses the tension between Isch and Rohrer on causal language, and turns to the coding projects. Take the break after Part 3.

## Source conventions

Figures from Bergstrom and West, *Thinking Clearly with Data*, Rohrer, and Isch et al. are copied from the assigned Week 10 readings. DAGs, simulations, and the HRT comparison plot are generated by `make-figures.py`; the chain, fork, collider, and smoking–COVID charts use simulated data, not data from the cited studies. Examples outside the readings (the four opening cases, HRT, police and crime, Facebook deactivation, Sesame Street, Sinclair, smoking and COVID) are cited on their slides. Slide numbers include the automatic title slide.

## Slide-by-slide notes

'''

parts = re.split(r"^## ", source, flags=re.M)[1:]

def slide_id(part):
    title = part.split("\n", 1)[0]
    explicit = re.search(r"\{#([^\s.}]+)", title)
    if explicit:
        return explicit.group(1)
    title = re.sub(r"\s+\{[^}]+\}$", "", title)
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")

for index, part in enumerate(parts):
    number = index + 2
    title, body = part.split("\n", 1)
    title = re.sub(r"\s+\{[^}]+\}$", "", title)
    matches = re.findall(r"::: notes\n(.*?)\n:::", body, re.S)
    if len(matches) != 1:
        raise ValueError(f"Expected one notes block: {title}; found {len(matches)}")
    next_title = None
    if index + 1 < len(parts):
        next_title = re.sub(r"\s+\{[^}]+\}$", "", parts[index + 1].split("\n", 1)[0])
    transition = f'**Transition:** next, {next_title}' if next_title else "**Close:** Pause for final questions and collect the exit response."
    intro += f"### Slide {number}: {title}\n\n{matches[0].strip()}\n\n{transition}\n\n"

(base / "instructor-notes.qmd").write_text(intro)
print(f"Synchronized notes for {len(parts)} teaching slides.")
