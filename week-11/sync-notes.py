"""Generate Week 11 presenter, visible-notes, and instructor-notes views."""
from pathlib import Path
import re

base = Path(__file__).resolve().parent
source = (base / "index.qmd").read_text()

for name, visible in (("presenter.qmd", "false"), ("with-notes.qmd", "true")):
    deck = source.replace("filters: [add-transitions.lua, strip-speaker-notes.lua]\n", "filters: [add-transitions.lua]\n")
    deck = deck.replace("  revealjs:\n", f"  revealjs:\n    show-notes: {visible}\n", 1)
    (base / name).write_text(deck)

intro = '''---
title: "Week 11: Instructor Notes"
subtitle: "Experiments, from DAGs to Design · COMM 5220"
format:
  html:
    theme: cosmo
    toc: true
    toc-depth: 3
    number-sections: false
    embed-resources: true
    css: notes.css
lang: en
---

[Open presenter slides](presenter.html) · [Open slides with visible notes](with-notes.html)

## Teaching approach

The seminar runs in five parts. **Part 1** rebuilds Rohrer's DAG vocabulary through one running example—whether attending a selective college pays off—with interactive confounder, collider, and mediator paths; it adds a verbal and graphical explanation of collider bias, including the famous-actor selection example, and places mediation and moderation beside the DAG concepts. Advanced transfer exercises remain hidden as optional backup slides. **Part 2** moves from DAGs to experimental design: the Fundamental Problem of Causal Inference, scientific versus statistical solutions, Druckman's 2×2 typology, the assumptions behind randomization, the different jobs of assignment, sampling, and sample size, experimental settings, the priority of experimental over mundane realism for theory tests, a student exercise on fact/theory/policy goals, treatment validity, the four validity questions, and a qualified external-validity argument based on effect heterogeneity and moderator coverage. **Part 3** is a full live deep-dive on Correll, Benard, and Paik (2007): students distinguish the population wage-gap puzzle from the randomized parental-status-cue estimand, propose the design, inspect the lab and field-audit procedures, and critique what each identifies. **Part 4** repeats the structure for Craig and Richeson (2014/2015), explicitly separating actual demographic change from randomized message exposure, calibrating the corrected Study 1 evidence, and comparing measured mediation with Studies 3a/3b's experimental manipulation of the proposed status-threat mechanism. **Part 5** synthesizes both cases and closes with a project application and exit question.

## Source conventions

Almost every DAG in Part 1 (the college-and-income chain/fork/collider/combined DAGs, the two "harder version" stretch DAGs, and the social-media capstone DAG) is drawn live by the scored interactive widget in `open-closed-simulation.html`, not a static image — the only static DAG still reused from Week 10 is Rohrer's own Figure 3 (genetic confounding), copied from `week-10/assets/`. New static DAGs for this week (the naive motherhood DAG, the statistical-vs-status-discrimination comparison, the randomized-design DAG, the three candidate DAGs for the racial-shift case, the full status-threat/assuaged-threat DAG, the mediation-vs-moderation pair, and the independence/SUTVA/exclusion-restriction violation DAGs) are generated by `make-figures.py`. Tables and figures from the three readings (Druckman's Tables 2.3/3.1; Correll, Benard, and Paik's Tables 1 and 6; Craig and Richeson's Figure 1 and Tables 2–3) are cropped directly from the source PDFs and credited on their slides. Slide numbers include the automatic title slide.

## Slide-by-slide script

'''

parts = re.split(r"^## ", source, flags=re.M)[1:]
visible_parts = [p for p in parts if 'visibility="hidden"' not in p.split("\n", 1)[0]]
hidden_parts = [p for p in parts if 'visibility="hidden"' in p.split("\n", 1)[0]]

def slide_id(part):
    title = part.split("\n", 1)[0]
    explicit = re.search(r"\{#([^\s.}]+)", title)
    if explicit:
        return explicit.group(1)
    title = re.sub(r"\s+\{[^}]+\}$", "", title)
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")

for index, part in enumerate(visible_parts):
    number = index + 2
    title, body = part.split("\n", 1)
    title = re.sub(r"\s+\{[^}]+\}$", "", title)
    matches = re.findall(r"::: notes\n(.*?)\n:::", body, re.S)
    if len(matches) != 1:
        raise ValueError(f"Expected one notes block: {title}; found {len(matches)}")
    intro += f"### Slide {number}: {title}\n\n{matches[0].strip()}\n\n"

if hidden_parts:
    intro += "## Hidden backup slides\n\nThese slides remain in the source but are omitted from the visible presentation.\n\n"
    for part in hidden_parts:
        title, body = part.split("\n", 1)
        title = re.sub(r"\s+\{[^}]+\}$", "", title)
        matches = re.findall(r"::: notes\n(.*?)\n:::", body, re.S)
        if len(matches) != 1:
            raise ValueError(f"Expected one notes block: {title}; found {len(matches)}")
        intro += f"### Backup: {title}\n\n{matches[0].strip()}\n\n"

(base / "instructor-notes.qmd").write_text(intro)
print(f"Synchronized notes for {len(visible_parts)} visible teaching slides and {len(hidden_parts)} hidden backups.")
