"""Generate Week 12 presenter, visible-notes, and instructor-notes views."""
from pathlib import Path
import re

base = Path(__file__).resolve().parent
source = (base / "index.qmd").read_text()

for name, visible in (("presenter.qmd", "false"), ("with-notes.qmd", "true")):
    deck = source.replace("filters: [add-transitions.lua, strip-speaker-notes.lua]\n", "filters: [add-transitions.lua]\n")
    deck = deck.replace("  revealjs:\n", f"  revealjs:\n    show-notes: {visible}\n", 1)
    (base / name).write_text(deck)

intro = '''---
title: "Week 12: Instructor Notes"
subtitle: "Mechanisms, Moderators, and Natural Experiments · COMM 5220"
format:
  html:
    theme: cosmo
    toc: true
    toc-depth: 3
    number-sections: false
    embed-resources: true
    css: notes.css
lang: en
---

[Open presenter slides](presenter.html) · [Open slides with visible notes](with-notes.html)

## Teaching approach

The seminar runs in five parts. **Part 1** finishes Week 11's second case, Craig and Richeson (2014/2015), which manipulated the proposed status-threat mechanism rather than only measuring it. **Part 2** revisits mediation with Mutz and Rao (2018): the ideology–latte gap, four candidate third variables classified as confounders or mediators, the ideology coefficient across models, and why a cross-sectional survey cannot distinguish a mediating from a confounding nationalism. **Part 3** revisits moderation with Petty, Cacioppo, and Goldman (1981): involvement × argument quality and involvement × source expertise, plotted from Table 1. **Part 4** builds a natural-experiment toolbox from Dunning (2012, ch. 1) and Grosz et al. (2024): lotteries, as-if random events, regression discontinuity, instrumental variables, and before/after designs, each as a naive DAG beside a design DAG, with their assumptions, Dunning's contrast cases, and his three evaluative dimensions. **Part 5** works through Bol, de Vaan, and van de Rijt (2018) and Balcells and Torrats-Espinosa (2018) in depth and compares them. Take the break between Parts 3 and 4.

## Source conventions

DAGs and the Petty et al. interaction plot are generated by `make-figures.py`; the interaction plot uses Table 1 cell means averaged over the third factor. Figures and tables from the readings are cropped from the PDFs (and, for Balcells and Torrats-Espinosa, the SI) via the reading summaries in `Readings/week 12/`. Numbers that notes attribute to the reading summaries (for example, Bol et al.'s win rates among applicants and the Balcells placebo check) are summary calculations, not reported in the papers. The Craig and Richeson section is carried over from Week 11. Slide numbers include the automatic title slide.

## Slide-by-slide script

'''

parts = re.split(r"^## ", source, flags=re.M)[1:]
visible_parts = [p for p in parts if 'visibility="hidden"' not in p.split("\n", 1)[0]]
hidden_parts = [p for p in parts if 'visibility="hidden"' in p.split("\n", 1)[0]]

def slide_id(part):
    title = part.split("\n", 1)[0]
    explicit = re.search(r"\{#([^\s.}]+)", title)
    if explicit:
        return explicit.group(1)
    title = re.sub(r"\s+\{[^}]+\}$", "", title)
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")

for index, part in enumerate(visible_parts):
    number = index + 2
    title, body = part.split("\n", 1)
    title = re.sub(r"\s+\{[^}]+\}$", "", title)
    matches = re.findall(r"::: notes\n(.*?)\n:::", body, re.S)
    if len(matches) != 1:
        raise ValueError(f"Expected one notes block: {title}; found {len(matches)}")
    intro += f"### Slide {number}: {title}\n\n{matches[0].strip()}\n\n"

if hidden_parts:
    intro += "## Hidden backup slides\n\nThese slides remain in the source but are omitted from the visible presentation.\n\n"
    for part in hidden_parts:
        title, body = part.split("\n", 1)
        title = re.sub(r"\s+\{[^}]+\}$", "", title)
        matches = re.findall(r"::: notes\n(.*?)\n:::", body, re.S)
        if len(matches) != 1:
            raise ValueError(f"Expected one notes block: {title}; found {len(matches)}")
        intro += f"### Backup: {title}\n\n{matches[0].strip()}\n\n"

(base / "instructor-notes.qmd").write_text(intro)
print(f"Synchronized notes for {len(visible_parts)} visible teaching slides and {len(hidden_parts)} hidden backups.")
